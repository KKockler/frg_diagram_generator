// TikZ export. Lines use the exact same geometry as the canvas/PDF (explicit paths);
// labels become real TeX \nodes so they are typeset by the paper's own fonts.
import type { FrgDocument } from '../model/types';
import type { Cmd } from '../geometry/path';
import { buildScene } from '../render/scene';
import { isTex, type BBox, type PathPrim, type TexPrim } from '../render/primitives';
import { pdfSourceBlock } from './io';

export interface TikzOptions {
  /** 1 model unit = scale pt. */
  scale: number;
  only?: Set<string>;
  /** Embed the editable source as a comment block (re-open the .tex in the editor). */
  source?: string;
  /** Wrap in a compilable standalone document. */
  standalone?: boolean;
}

const n = (x: number) => (Math.round(x * 1000) / 1000).toString();
const pt = (p: { x: number; y: number }) => `(${n(p.x)},${n(p.y)})`;

function pathSpec(cmds: Cmd[]): string {
  return cmds
    .map((c) => {
      switch (c.op) {
        case 'M':
          return pt(c.p);
        case 'L':
          return `-- ${pt(c.p)}`;
        case 'C':
          return `.. controls ${pt(c.c1)} and ${pt(c.c2)} .. ${pt(c.p)}`;
        case 'Z':
          return '-- cycle';
      }
    })
    .join(' ');
}

class Colors {
  private map = new Map<string, string>();
  name(hex: string): string {
    const h = hex.replace('#', '').toUpperCase();
    if (h === '000000') return 'black';
    if (h === 'FFFFFF') return 'white';
    if (!this.map.has(h)) this.map.set(h, `frgc${this.map.size}`);
    return this.map.get(h)!;
  }
  defs(): string[] {
    return [...this.map].map(([h, name]) => `\\definecolor{${name}}{HTML}{${h}}`);
  }
}

function drawPath(p: PathPrim, colors: Colors, scale: number): string {
  const opts: string[] = [];
  const cmd = p.fill && p.stroke ? '\\filldraw' : p.fill ? '\\fill' : '\\draw';
  if (p.stroke) opts.push(`draw=${colors.name(p.stroke)}`, `line width=${n((p.width ?? 1) * scale)}pt`);
  if (p.fill) opts.push(`fill=${colors.name(p.fill)}`);
  if (p.fill && p.opacity !== undefined && p.opacity < 1) opts.push(`fill opacity=${n(p.opacity)}`);
  if (p.cap && p.cap !== 'butt') opts.push(`line cap=${p.cap}`);
  if (p.join && p.join !== 'round') opts.push(`line join=${p.join}`);
  if (p.dash) {
    const [on, off] = p.dash;
    opts.push(`dash pattern=on ${n(Math.max(on, 0.001) * scale)}pt off ${n(off * scale)}pt`);
  }
  return `${cmd}[${opts.join(', ')}] ${pathSpec(p.d)};`;
}

function drawTex(p: TexPrim, colors: Colors, scale: number): string {
  const { box, size, source, color } = p.tex;
  const s = size * scale;
  const c = { x: box.x + box.w / 2, y: box.y + box.h / 2 };
  return `\\node[inner sep=0pt, text=${colors.name(color)}, font=\\fontsize{${n(s)}}{${n(s * 1.2)}}\\selectfont] at ${pt(c)} {$${source}$};`;
}

/** Wrap the base64 source block into TeX comment lines. */
function sourceComment(json: string): string {
  return (pdfSourceBlock(json).match(/.{1,100}/g) ?? []).map((l) => `%${l}`).join('\n');
}

export function toTikz(doc: FrgDocument, opts: TikzOptions): { tex: string; bbox: BBox | null } {
  const scene = buildScene(doc, opts.only);
  const colors = new Colors();
  const body = scene.prims.map((p) => (isTex(p) ? drawTex(p, colors, opts.scale) : drawPath(p, colors, opts.scale)));
  const lines = [
    '% fRG diagram, generated by the fRG Diagram Editor. Needs \\usepackage{tikz}.',
    ...(opts.source ? ['% Editable source (open this file in the editor):', sourceComment(opts.source)] : []),
    `\\begin{tikzpicture}[x=${n(opts.scale)}pt, y=-${n(opts.scale)}pt, line join=round]`,
    ...colors.defs().map((d) => '  ' + d),
    ...body.map((b) => '  ' + b),
    '\\end{tikzpicture}',
  ];
  let tex = lines.join('\n') + '\n';
  if (opts.standalone) {
    tex = `\\documentclass[tikz,border=1pt]{standalone}\n\\usepackage{lmodern}\n\\usepackage{amsmath,amssymb}\n\\begin{document}\n${tex}\\end{document}\n`;
  }
  return { tex, bbox: scene.bbox };
}
